import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Buffer } from 'node:buffer';
import { preparePages } from './prepare-pages.mjs';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'tsudowa-pages-test-'));
const src = path.join(temp, 'export'), dst = path.join(temp, 'pages');
fs.mkdirSync(path.join(src, 'assets/node_modules/.pnpm/icons/node_modules/icons'), { recursive: true });
const asset = 'assets/node_modules/.pnpm/icons/node_modules/icons/font.ttf';
fs.writeFileSync(path.join(src, asset), Buffer.from([0, 1, 0, 0, 20]));
fs.writeFileSync(path.join(src, 'index.html'), '<script src="entry.js"></script>');
fs.writeFileSync(path.join(src, 'entry.js'), `const uri="/${asset}";`);
assert.deepEqual(preparePages(src, dst), { files: 3, assets: 1 });
const js = fs.readFileSync(path.join(dst, 'entry.js'), 'utf8');
assert.ok(!js.includes('node_modules'));
const uri = /"\/(assets\/files\/[^\"]+)"/.exec(js)?.[1];
assert.ok(uri);
assert.deepEqual(fs.readFileSync(path.join(dst, uri)), fs.readFileSync(path.join(src, asset)));
assert.ok(fs.readFileSync(path.join(src, 'entry.js'), 'utf8').includes(asset));
assert.throws(() => preparePages(src, src), /separate/);
assert.throws(() => preparePages(src, path.join(src, 'nested')), /separate/);
assert.throws(() => preparePages(src, dst), /new output/);
console.log('Pages asset regression checks passed. Fixture retained at: ' + temp);
